function ArticlePicker({
  articles,
  selectedArticle,
  usedArticleIds,
  onSelect,
}) {
  const [open, setOpen] = useState(false);
  const [searchText, setSearchText] = useState("");

  const containerRef = useRef(null);

  useEffect(() => {
    const handleClickOutside = (event) => {
      if (
        containerRef.current &&
        !containerRef.current.contains(event.target)
      ) {
        setOpen(false);
      }
    };

    document.addEventListener("mousedown", handleClickOutside);

    return () => {
      document.removeEventListener("mousedown", handleClickOutside);
    };
  }, []);


  const filteredArticles = articles.filter((article) => {
    const text = article.value || "";

    const search = searchText.trim().toLowerCase();

    if (!search) {
      return true;
    }

    return (
      String(article.id).toLowerCase().includes(search) ||
      text.toLowerCase().includes(search)
    );
  });


  return (
    <div ref={containerRef} className="relative">

      {/* ================================================================ */}
      {/* SELECT BUTTON */}
      {/* ================================================================ */}

      <button
        type="button"
        onClick={() => setOpen((previous) => !previous)}
        className="flex min-h-[58px] w-full items-center justify-between gap-3 rounded-xl border border-gray-300 bg-white px-4 text-right transition hover:border-gray-400 focus:border-blue-500"
      >

        <div className="min-w-0">

          {selectedArticle ? (
            <>
              <p className="text-xs font-semibold text-blue-600">
                المادة {selectedArticle.id}
              </p>

              <p className="mt-1 line-clamp-1 text-sm text-gray-700">
                {selectedArticle.value}
              </p>
            </>
          ) : (
            <p className="text-sm text-gray-500">
              اختر المادة التي تريد تعديلها
            </p>
          )}

        </div>

        <ChevronDown
          className={`h-5 w-5 shrink-0 text-gray-500 transition ${open ? "rotate-180" : ""
            }`}
        />

      </button>


      {/* ================================================================ */}
      {/* FLOATING ARTICLE WINDOW */}
      {/* ================================================================ */}

      {open && (
        <div className="absolute right-0 top-[calc(100%+8px)] z-50 w-full min-w-[320px] overflow-hidden rounded-2xl border border-gray-200 bg-white shadow-2xl">

          {/* SEARCH */}

          <div className="border-b border-gray-200 bg-gray-50 p-3">

            <div className="relative">

              <Search className="absolute right-3 top-1/2 h-4 w-4 -translate-y-1/2 text-gray-400" />

              <input
                type="text"
                value={searchText}
                onChange={(event) =>
                  setSearchText(event.target.value)
                }
                placeholder="ابحث في المواد..."
                className="w-full rounded-xl border border-gray-300 bg-white py-2.5 pr-9 pl-3 text-sm text-gray-900 outline-none focus:border-blue-500"
                autoFocus
              />

            </div>

          </div>


          {/* ARTICLES */}

          <div className="max-h-[350px] overflow-y-auto p-2">

            {filteredArticles.length === 0 ? (
              <div className="px-4 py-8 text-center text-sm text-gray-500">
                لا توجد مواد مطابقة للبحث
              </div>
            ) : (
              filteredArticles.map((article) => {

                const isSelected =
                  selectedArticle &&
                  String(selectedArticle.id) ===
                  String(article.id);

                const isUsed =
                  usedArticleIds.includes(String(article.id));

                return (
                  <button
                    key={article.id}
                    type="button"
                    disabled={isUsed && !isSelected}
                    onClick={() => {
                      onSelect(article);
                      setOpen(false);
                      setSearchText("");
                    }}
                    className={`mb-1 w-full rounded-xl p-3 text-right transition last:mb-0 ${isSelected
                      ? "border border-blue-200 bg-blue-50"
                      : isUsed
                        ? "cursor-not-allowed opacity-40"
                        : "hover:bg-gray-50"
                      }`}
                  >

                    <div className="mb-1 flex items-center justify-between gap-3">

                      <span className="rounded-lg bg-gray-100 px-2 py-1 text-xs font-bold text-gray-700">
                        المادة {article.id}
                      </span>

                      {isUsed && !isSelected && (
                        <span className="text-xs text-red-500">
                          مستخدمة
                        </span>
                      )}

                      {isSelected && (
                        <Check className="h-4 w-4 text-blue-600" />
                      )}

                    </div>

                    <p className="line-clamp-3 text-sm leading-6 text-gray-700">
                      {article.value}
                    </p>

                  </button>
                );
              })
            )}

          </div>

        </div>
      )}

    </div>
  );
}


