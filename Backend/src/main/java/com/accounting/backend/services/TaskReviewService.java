package com.accounting.backend.services;

import java.time.LocalDateTime;
import java.util.LinkedHashMap;
import java.util.Map;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import com.accounting.backend.dto.TaskRequest;
import com.accounting.backend.dto.TaskResponse;
import com.accounting.backend.entities.Contract;
import com.accounting.backend.entities.Task;
import com.accounting.backend.enums.ContractStatus;
import com.accounting.backend.enums.ContractType;
import com.accounting.backend.enums.NotificationType;
import com.accounting.backend.enums.SubTaskStatus;
import com.accounting.backend.enums.TaskStatus;
import com.accounting.backend.repositories.ContractRepository;
import com.accounting.backend.repositories.TaskRepository;

/**
 * Manager review workflow for amendment tasks:
 * amendment is generated by the employee (persisted as a UPDATING Contract with
 * PENDING_APPROVAL status), the task becomes DONE, then the manager reviews it
 * on /review/:taskId and either approves (task ACCEPTED + amendment APPROVED)
 * or returns it for modification (task back to IN_PROGRESS, amendment stays pending).
 */
@Service
public class TaskReviewService {

    @Autowired
    private TaskRepository taskRepository;
    @Autowired
    private ContractRepository contractRepository;
    @Autowired
    private TaskService taskService;
    @Autowired
    private NotificationService notificationService;

    @Transactional(readOnly = true)
    public Map<String, Object> getReviewData(Long taskId, Long callerId) {
        taskService.assertManager(callerId);
        Task task = taskRepository.findById(taskId)
                .orElseThrow(() -> new IllegalArgumentException("Task not found"));

        Map<String, Object> result = new LinkedHashMap<>();
        result.put("task", TaskResponse.mapToResponse(task));
        result.put("amendment", describe(resolveAmendment(task)));
        result.put("originalContract", describe(resolveOriginalContract(task)));
        return result;
    }

    @Transactional
    public TaskResponse approveTask(Long taskId, Long callerId) {
        taskService.assertManager(callerId);
        Task task = taskRepository.findById(taskId)
                .orElseThrow(() -> new IllegalArgumentException("Task not found"));

        // Reuse the exact existing accept flow (PUT /tasks/{id} with ACCEPTED)
        TaskRequest request = new TaskRequest();
        request.setStatus(TaskStatus.ACCEPTED);
        TaskResponse updated = taskService.updateTask(taskId, request, callerId);

        Contract amendment = resolveAmendment(task);
        if (amendment != null) {
            amendment.setStatus(ContractStatus.APPROVED);
            amendment.setUpdatedAt(LocalDateTime.now());
            contractRepository.save(amendment);
        }

        notifyWorkers(task, "Task approved",
                "تم اعتماد المهمة: " + task.getTitle(),
                NotificationType.TASK_COMPLETED);
        return updated;
    }

    @Transactional
    public TaskResponse returnTaskForModification(Long taskId, Long callerId) {
        taskService.assertManager(callerId);
        Task task = taskRepository.findById(taskId)
                .orElseThrow(() -> new IllegalArgumentException("Task not found"));
        if (task.getStatus() != TaskStatus.DONE) {
            throw new IllegalStateException("Only a task waiting for review can be returned");
        }

        task.setStatus(TaskStatus.IN_PROGRESS);
        for (var subTask : TaskResponse.liveSubTasks(task)) {
            if (subTask.getStatus() == SubTaskStatus.DONE) {
                subTask.setStatus(SubTaskStatus.IN_PROGRESS);
            }
        }
        Task saved = taskRepository.save(task);

        // The proposed amendment stays PENDING_APPROVAL so the employee can
        // generate an updated one; the original contract is never touched.
        notifyWorkers(saved, "Task returned",
                "تم إعادة المهمة للتعديل: " + saved.getTitle(),
                NotificationType.TASK_ASSIGNED);
        return TaskResponse.mapToResponse(saved);
    }

    private Contract resolveAmendment(Task task) {
        if (task.getId() == null) {
            return null;
        }
        Contract linked = contractRepository.findFirstByTask_IdOrderByIdDesc(task.getId()).orElse(null);
        if (linked != null) {
            return linked;
        }
        if (task.getCompany() != null) {
            Long companyId = task.getCompany().getId();
            return contractRepository
                    .findFirstByCompany_IdAndTypeAndStatusOrderByIdDesc(
                            companyId, ContractType.UPDATING, ContractStatus.PENDING_APPROVAL)
                    .or(() -> contractRepository.findFirstByCompany_IdAndTypeOrderByIdDesc(
                            companyId, ContractType.UPDATING))
                    .orElse(null);
        }
        return null;
    }

    private Contract resolveOriginalContract(Task task) {
        if (task.getCompany() == null) {
            return null;
        }
        return contractRepository
                .findFirstByCompany_IdAndTypeOrderByIdDesc(task.getCompany().getId(), ContractType.CREATING)
                .orElse(null);
    }

    private Map<String, Object> describe(Contract contract) {
        if (contract == null) {
            return null;
        }
        Map<String, Object> info = new LinkedHashMap<>();
        info.put("id", contract.getId());
        info.put("status", contract.getStatus());
        info.put("filePath", contract.getFilePath());
        info.put("ocrData", contract.getOcrData());
        info.put("createdAt", contract.getCreatedAt());
        info.put("companyId", contract.getCompany() != null ? contract.getCompany().getId() : null);
        info.put("companyName", contract.getCompany() != null ? contract.getCompany().getName() : null);
        return info;
    }

    private void notifyWorkers(Task task, String title, String message, NotificationType type) {
        if (task.getAssignedTo() != null) {
            notificationService.createNotification(task.getAssignedTo().getId(), title, message, type, task.getId());
        }
        java.util.Set<Long> notified = new java.util.HashSet<>();
        if (task.getAssignedTo() != null) {
            notified.add(task.getAssignedTo().getId());
        }
        for (var worker : TaskResponse.workingEmployees(task)) {
            if (notified.add(worker.getId())) {
                notificationService.createNotification(worker.getId(), title, message, type, task.getId());
            }
        }
    }
}
